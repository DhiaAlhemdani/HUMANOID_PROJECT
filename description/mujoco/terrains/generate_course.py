#!/usr/bin/env python3
"""Generate a G1 walking course (uneven fields, ramps, curbs / plateaus, stairs) as a MuJoCo module.

One YAML (config/terrains/g1/<name>.yaml, key `course`) lists features along world +x; `mirror_x: true`
duplicates every feature at -x so the backward ladder (tests/tuning/suite/backward.json) meets the same
course as the forward one. Features:

  uneven_fields: {name, x: [x0, x1], seed, cell (m, default 0.5), edge_blend (m, default 0), tiles}
      tiles of the style in `tiles` (per field or course-wide: a generate_uneven_terrain.py params file,
      relative to the YAML; only its height / profile / depth / jitter / gap settings are used), edge_blend caps the heights
      so the field rises from the floor at its x-edges (the same cap as clear_patch.blend_radius)
  ramps:         {name, x: [x0, x1], z: [z0, z1]}   top face from (x0, z0) to (x1, z1), full width
  plateaus:      {name, x: [x0, x1], top}            a box from the floor to `top` (a curb when alone)
  stairs:        {name, x0, riser, tread, count, down: false}  `count` plateaus of `tread` depth rising
                 (or falling from count*riser) by `riser` each; a landing is a plateau after them

The robot spawns at the origin facing +x, so keep |x| < ~1 m flat. MuJoCo only: the MPC uses no terrain
map (it walks blind), so no RViz twin is generated. Materials come from the scene's terrain_materials.xml.

  python3 description/mujoco/terrains/generate_course.py --params config/terrains/g1/slope_5.yaml \\
      --mjcf description/mujoco/terrains/g1_slope_5.xml [--check]
"""

import argparse
import copy
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_uneven_terrain as uneven  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
COLORS = {"ramp": "0.85 0.9 1 1", "plateau": "0.9 0.9 0.9 1", "stair": "0.95 0.9 0.8 1", "tile": "1 1 1 1"}
THICKNESS = 0.05  # ramp slab


def finite(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def span(feature, key="x"):
    x0, x1 = feature[key]
    if not (finite(x0) and finite(x1) and x1 > x0):
        raise ValueError(f"{feature.get('name')}: {key} must be [lo, hi] with hi > lo")
    return float(x0), float(x1)


def expand_stairs(config):
    """Stairs become plateaus so every feature kind but ramps is a box from the floor."""
    plateaus = list(config.get("plateaus", []))
    for stair in config.get("stairs", []):
        riser, tread, count = stair["riser"], stair["tread"], int(stair["count"])
        if not (finite(riser) and riser > 0 and finite(tread) and tread > 0 and count >= 1):
            raise ValueError(f"{stair.get('name')}: riser, tread > 0 and count >= 1")
        for k in range(count):
            level = count - k if stair.get("down", False) else k + 1
            x0 = stair["x0"] + k * tread
            plateaus.append({"name": f"{stair['name']}_{k + 1:02d}", "x": [x0, x0 + tread], "top": level * riser,
                             "kind": "stair"})
    return plateaus


def mirrored(features, key_z=None):
    out = []
    for f in features:
        g = copy.deepcopy(f)
        g["name"] = f["name"] + "_m"
        g["x"] = [-f["x"][1], -f["x"][0]]
        if key_z and key_z in f:
            g[key_z] = list(reversed(f[key_z]))
        out.append(g)
    return out


def field_heights(tile, x_length, edge_blend):
    heights = uneven.generate_heights(tile)
    if edge_blend <= 0:
        return heights
    nx = tile["grid"][0]
    top = tile["height"]["max"]
    pitch = x_length / nx
    if top * pitch / edge_blend > tile["height"]["adjacent_difference"]["max"] + 1e-12:
        raise ValueError("edge_blend too short: height.max * cell / edge_blend exceeds adjacent_difference.max")
    out = []
    for i, row in enumerate(heights):
        d = min(i + 0.5, nx - i - 0.5) * pitch  # distance of the cell centre to the nearer x-edge
        out.append([min(h, top * d / edge_blend) for h in row])
    return out


def build_mjcf(config, params_dir):
    half_width, friction = float(config["half_width"]), uneven.fmt(config["friction"])
    if not (finite(half_width) and half_width > 0):
        raise ValueError("half_width must be a positive length")
    mirror = bool(config.get("mirror_x", False))
    root = ET.Element("mujoco", model=config["model"])
    root.append(ET.Comment(f" Generated by generate_course.py; edit {config.get('source', 'the course YAML')}. "))
    world = ET.SubElement(root, "worldbody")
    intervals = []

    fields = list(config.get("uneven_fields", []))
    fields += mirrored(fields) if mirror else []
    for field in fields:
        x0, x1 = span(field)
        cell = float(field.get("cell", 0.5))
        tile = yaml.safe_load((params_dir / field.get("tiles", config.get("tiles", ""))).read_text())["uneven_terrain"]
        tile.update(size=[x1 - x0, 2 * half_width], grid=[max(1, round((x1 - x0) / cell)), max(1, round(2 * half_width / cell))],
                    seed=int(field["seed"]), clear_patch={"center": [0.0, 0.0], "size": [0.0, 0.0]})
        tile["base"] = {"pos": [(x0 + x1) / 2, 0.0, 0.0], "yaw": 0.0}
        uneven.validate(tile)
        heights = field_heights(tile, x1 - x0, float(field.get("edge_blend", 0.0)))
        body = ET.SubElement(world, "body", name=field["name"], pos=uneven.fmt(tile["base"]["pos"]))
        for block in uneven.generate_blocks(tile, heights):
            ET.SubElement(body, "geom", name=f"{field['name']}_{block['name']}", type="box", pos=uneven.fmt(block["pos"]),
                          size=uneven.fmt([v / 2 for v in block["size"]]), material="studio_terrain",
                          rgba=COLORS["tile"], friction=friction)
        intervals.append((x0, x1, field["name"]))

    ramps = list(config.get("ramps", []))
    ramps += mirrored(ramps, "z") if mirror else []
    for ramp in ramps:
        (x0, x1), (z0, z1) = span(ramp), ramp["z"]
        if not (finite(z0) and finite(z1) and min(z0, z1) >= 0):
            raise ValueError(f"{ramp['name']}: z must be nonnegative heights")
        length, angle = math.hypot(x1 - x0, z1 - z0), math.atan2(z1 - z0, x1 - x0)
        # A slab rotated about y whose top face runs from (x0, z0) to (x1, z1).
        center = [(x0 + x1) / 2 + THICKNESS * math.sin(angle), 0.0, (z0 + z1) / 2 - THICKNESS * math.cos(angle)]
        ET.SubElement(world, "geom", name=ramp["name"], type="box", pos=uneven.fmt(center),
                      size=uneven.fmt([length / 2, half_width, THICKNESS]), euler=uneven.fmt([0, -angle, 0]),
                      material="studio_terrain", rgba=COLORS["ramp"], friction=friction)
        intervals.append((x0, x1, ramp["name"]))

    plateaus = expand_stairs(config)
    plateaus += mirrored(plateaus) if mirror else []
    for plateau in plateaus:
        (x0, x1), top = span(plateau), float(plateau["top"])
        if not (finite(top) and top > 0):
            raise ValueError(f"{plateau['name']}: top must be a positive height")
        ET.SubElement(world, "geom", name=plateau["name"], type="box", pos=uneven.fmt([(x0 + x1) / 2, 0.0, (top - 0.1) / 2]),
                      size=uneven.fmt([(x1 - x0) / 2, half_width, (top + 0.1) / 2]), material="studio_terrain",
                      rgba=COLORS[plateau.get("kind", "plateau")], friction=friction)
        intervals.append((x0, x1, plateau["name"]))

    intervals.sort()
    for (a0, a1, an), (b0, b1, bn) in zip(intervals, intervals[1:]):
        if b0 < a1 - 1e-9:
            raise ValueError(f"features overlap along x: {an} [{a0}, {a1}] and {bn} [{b0}, {b1}]")
    if any(x0 < 0.5 < x1 or x0 < -0.5 < x1 or -0.5 <= x0 <= 0.5 for x0, x1, _ in intervals):
        raise ValueError("keep |x| <= 0.5 m clear: the robot spawns at the origin")
    return root


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--params", type=Path, required=True)
    parser.add_argument("--mjcf", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="verify the generated file without writing")
    args = parser.parse_args()
    config = yaml.safe_load(args.params.read_text())["course"]
    config.setdefault("source", str(args.params.resolve().relative_to(ROOT)) if args.params.resolve().is_relative_to(ROOT)
                      else args.params.name)
    content = uneven.xml_text(build_mjcf(config, args.params.resolve().parent))
    if args.check:
        if not args.mjcf.is_file() or args.mjcf.read_text() != content:
            parser.error(f"stale generated file: {args.mjcf}")
    else:
        args.mjcf.write_text(content)
        print("wrote", args.mjcf)


if __name__ == "__main__":
    main()
